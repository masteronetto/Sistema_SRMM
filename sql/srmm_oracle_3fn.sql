    CONSTRAINT PK_ROLE_REQUESTS PRIMARY KEY (ID_REQUEST),
    CONSTRAINT CK_ROLE_REQUESTS_ESTADO CHECK (ESTADO IN ('Pendiente', 'Aprobada', 'Rechazada'))
);

