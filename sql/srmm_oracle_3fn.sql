CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    CONTRASENA VARCHAR2(255) NOT NULL,
    ROL_ACCESO VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ROL CHECK (ROL_ACCESO IN ('Administrador', 'Mecanico', 'Operador', 'Usuario'))
);

CREATE TABLE PLANES_MANTENCION (
    ID_PLAN NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    NOMBRE_PLAN VARCHAR2(100) NOT NULL,
    INTERVALO_HORAS NUMBER(12,2) NOT NULL,
    DESCRIPCION CLOB,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PLANES_MANTENCION PRIMARY KEY (ID_PLAN),
    CONSTRAINT UK_PLANES_MANTENCION_NOMBRE UNIQUE (NOMBRE_PLAN),
    CONSTRAINT CK_PLANES_MANTENCION_INTERVALO CHECK (INTERVALO_HORAS > 0)
);

CREATE TABLE MAQUINARIA (
    ID_MAQUINA NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    MODELO_EQUIPO VARCHAR2(120) NOT NULL,
    HOROMETRO_ACTUAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'Disponible' NOT NULL,
    ESPECIFICACIONES CLOB,
    PLANES_MANTENCION_ID_PLAN NUMBER(19),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MAQUINARIA PRIMARY KEY (ID_MAQUINA),
    CONSTRAINT CK_MAQUINARIA_HOROMETRO CHECK (HOROMETRO_ACTUAL >= 0),
    CONSTRAINT CK_MAQUINARIA_ESTADO CHECK (ESTADO IN ('Disponible', 'Arrendada', 'Mantencion', 'Bloqueada', 'No Operativa'))
);

CREATE TABLE MANTENIMIENTO (
    ID_MANTENCION NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    TIPO_SERVICIO VARCHAR2(60) NOT NULL,
    HOROMETRO_REGISTRO NUMBER(12,2) NOT NULL,
    DETALLE_TECNICO CLOB NOT NULL,
    FECHA_SERVICIO DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    USUARIOS_ID_USUARIO NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MANTENIMIENTO PRIMARY KEY (ID_MANTENCION),
    CONSTRAINT CK_MANTENIMIENTO_HOROMETRO CHECK (HOROMETRO_REGISTRO >= 0)
);

CREATE TABLE ARRIENDOS (
    ID_CONTRATO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    CLIENTE_ID NUMBER(19),
    HOROMETRO_ENTRADA NUMBER(12,2),
    HOROMETRO_SALIDA NUMBER(12,2),
    FECHA_INICIO DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    FECHA_FIN DATE,
    ESTADO_CONTRATO VARCHAR2(20) DEFAULT 'Activo' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ARRIENDOS PRIMARY KEY (ID_CONTRATO),
    CONSTRAINT CK_ARRIENDOS_ESTADO CHECK (ESTADO_CONTRATO IN ('Activo', 'Finalizado', 'Cancelado')),
    CONSTRAINT CK_ARRIENDOS_HOROMETRO_ENTRADA CHECK (HOROMETRO_ENTRADA IS NULL OR HOROMETRO_ENTRADA >= 0),
    CONSTRAINT CK_ARRIENDOS_HOROMETRO_SALIDA CHECK (HOROMETRO_SALIDA IS NULL OR HOROMETRO_SALIDA >= 0)
);

CREATE TABLE HISTORIAL_HOROMETRO (
    ID_REGISTRO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    VALOR_HORAS NUMBER(12,2) NOT NULL,
    FECHA_REGISTRO DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    ARRIENDOS_ID_CONTRATO NUMBER(19),
    ID_USUARIO NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HISTORIAL_HOROMETRO PRIMARY KEY (ID_REGISTRO),
    CONSTRAINT CK_HISTORIAL_HOROMETRO_VALOR CHECK (VALOR_HORAS >= 0)
);

CREATE TABLE INCIDENCIAS_MAQUINA (
    ID_INCIDENCIA NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    OPERADOR_ID NUMBER(19) NOT NULL,
    FECHA DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    DESCRIPCION CLOB NOT NULL,
    CRITICIDAD VARCHAR2(20) DEFAULT 'Media' NOT NULL,
    VINCULADA_MANTENIMIENTO NUMBER(1) DEFAULT 0 NOT NULL,
    MANTENIMIENTO_ID NUMBER(19),
    ESTADO VARCHAR2(20) DEFAULT 'Pendiente' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INCIDENCIAS_MAQUINA PRIMARY KEY (ID_INCIDENCIA),
    CONSTRAINT CK_INCIDENCIAS_MAQUINA_CRITICIDAD CHECK (CRITICIDAD IN ('Alta', 'Media', 'Baja')),
    CONSTRAINT CK_INCIDENCIAS_MAQUINA_ESTADO CHECK (ESTADO IN ('Pendiente', 'Resuelta')),
    CONSTRAINT CK_INCIDENCIAS_MAQUINA_VINCULADA CHECK (VINCULADA_MANTENIMIENTO IN (0,1))
);

CREATE TABLE ORDENES_TRABAJO (
    ID_ORDEN NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    MECANICO_ASIGNADO NUMBER(19) NOT NULL,
    TIPO_SERVICIO VARCHAR2(60) NOT NULL,
    DETALLE_TECNICO CLOB NOT NULL,
    FECHA_PROGRAMADA DATE NOT NULL,
    ESTADO_OT VARCHAR2(30) DEFAULT 'Programada' NOT NULL,
    ALERTA_RETRASO_ENVIADA NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ORDENES_TRABAJO PRIMARY KEY (ID_ORDEN),
    CONSTRAINT CK_ORDENES_TRABAJO_ESTADO CHECK (ESTADO_OT IN ('Programada', 'En Progreso', 'Completada', 'Cancelada')),
    CONSTRAINT CK_ORDENES_TRABAJO_ALERTA CHECK (ALERTA_RETRASO_ENVIADA IN (0,1))
);

CREATE TABLE ALERTAS_CRITICAS (
    ID_ALERTA NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    TIPO_ALERTA VARCHAR2(40) NOT NULL,
    ESTADO_ALERTA VARCHAR2(20) DEFAULT 'Pendiente' NOT NULL,
    PORCENTAJE_UMBRAL NUMBER(5,2) NOT NULL,
    HOROMETRO_CRITICO NUMBER(12,2) NOT NULL,
    REQUIERE_MANTENIMIENTO NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ALERTAS_CRITICAS PRIMARY KEY (ID_ALERTA),
    CONSTRAINT CK_ALERTAS_CRITICAS_TIPO CHECK (TIPO_ALERTA IN ('Critica', 'Advertencia')),
    CONSTRAINT CK_ALERTAS_CRITICAS_ESTADO CHECK (ESTADO_ALERTA IN ('Pendiente', 'Descartada', 'Resuelta')),
    CONSTRAINT CK_ALERTAS_CRITICAS_REQ CHECK (REQUIERE_MANTENIMIENTO IN (0,1))
);

CREATE TABLE BLOQUEOS_CRITICOS (
    ID_BLOQUEO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    MAQUINARIA_ID_MAQUINA NUMBER(19) NOT NULL,
    MOTIVO_BLOQUEO CLOB NOT NULL,
    COSTO_ESTIMADO_REPARACION NUMBER(12,2) DEFAULT 0 NOT NULL,
    ESTADO_BLOQUEO VARCHAR2(20) DEFAULT 'Activo' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_BLOQUEOS_CRITICOS PRIMARY KEY (ID_BLOQUEO),
    CONSTRAINT UK_BLOQUEOS_CRITICOS_MAQUINA UNIQUE (MAQUINARIA_ID_MAQUINA),
    CONSTRAINT CK_BLOQUEOS_CRITICOS_COSTO CHECK (COSTO_ESTIMADO_REPARACION >= 0),
    CONSTRAINT CK_BLOQUEOS_CRITICOS_ESTADO CHECK (ESTADO_BLOQUEO IN ('Activo', 'Resuelto'))
);

CREATE TABLE NOTIFICACIONES (
    ID_NOTIFICACION NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    USUARIO_ID NUMBER(19) NOT NULL,
    TIPO_NOTIFICACION VARCHAR2(40) NOT NULL,
    REFERENCIA_ID NUMBER(19),
    MENSAJE CLOB NOT NULL,
    LEIDA NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICACIONES PRIMARY KEY (ID_NOTIFICACION),
    CONSTRAINT CK_NOTIFICACIONES_LEIDA CHECK (LEIDA IN (0,1)),
    CONSTRAINT CK_NOTIFICACIONES_TIPO CHECK (TIPO_NOTIFICACION IN ('Orden Trabajo', 'Alerta Critica', 'Bloqueo', 'Mantenimiento Completado'))
);

CREATE TABLE NOTIFICACIONES_TIEMPO_REAL (
    ID_NOTIFICACION NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    ADMIN_ID NUMBER(19) NOT NULL,
    TIPO_NOTIFICACION VARCHAR2(40) NOT NULL,
    MAQUINA_ID NUMBER(19) NOT NULL,
    PRIORIDAD VARCHAR2(20) NOT NULL,
    HORAS_RESTANTES NUMBER(12,2),
    DETALLES CLOB NOT NULL,
    LEIDA NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICACIONES_TIEMPO_REAL PRIMARY KEY (ID_NOTIFICACION),
    CONSTRAINT CK_NOTIFICACIONES_TR_LEIDA CHECK (LEIDA IN (0,1)),
    CONSTRAINT CK_NOTIFICACIONES_TR_TIPO CHECK (TIPO_NOTIFICACION IN ('Alerta Critica', 'Orden Trabajo', 'Bloqueo')),
    CONSTRAINT CK_NOTIFICACIONES_TR_PRIORIDAD CHECK (PRIORIDAD IN ('Alta', 'Media', 'Baja')),
    CONSTRAINT CK_NOTIFICACIONES_TR_DETALLES_JSON CHECK (DETALLES IS JSON)
);

CREATE TABLE ROLE_REQUESTS (
    ID_REQUEST NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
